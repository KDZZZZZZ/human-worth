import { mockDesignApi } from "../tests/fixtures/design-api.js";
import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import fs from "node:fs";

const output = "artifacts/motion";
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || "msedge" });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.addInitScript(() => sessionStorage.setItem("human-worth-preview-data", "on"));
const page = await context.newPage();
await mockDesignApi(page);
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
const evidence = {};
const running = () => page.evaluate(() => document.getAnimations().filter((a) => a.playState === "running").map((a) => a.animationName));
try {
  await page.goto("http://127.0.0.1:18100/tasks/concept-library");
  const cover = page.locator(".chapter-cover").first();
  await cover.waitFor();
  await cover.scrollIntoViewIfNeeded();
  const rest = await cover.boundingBox();
  await cover.hover();
  await page.waitForTimeout(300);
  const raised = await cover.boundingBox();
  assert(raised.y < rest.y - 2, "The paper cover should visibly lift on hover");
  evidence.coverLift = rest.y - raised.y;
  await page.screenshot({ path: output + "/chapter-hover.png" });
  await cover.click();
  await page.waitForTimeout(400);
  const first = await page.locator(".book-front h3").innerText();
  await page.getByRole("button", { name: "Next →", exact: true }).evaluate((el) => el.click());
  evidence.pageTurn = await running();
  assert(evidence.pageTurn.includes("paper-turn"));
  await page.waitForTimeout(400);
  assert.notEqual(await page.locator(".book-front h3").innerText(), first);
  await page.getByRole("button", { name: "Choose this work", exact: true }).click();
  assert.equal(await page.locator(".work-actions button").first().getAttribute("aria-pressed"), "true");
  assert(!(await running()).includes("paper-turn"), "Choosing should not replay the reading animation");
  await page.goto("http://127.0.0.1:18100/submit?edit=fixture-submission");
  await page.getByRole("button", { name: "A small pause, a warm welcome back.", exact: true }).evaluate((el) => el.click());
  evidence.dialog = await running();
  assert(evidence.dialog.includes("paper-dialog"));
  await page.waitForTimeout(400);
  await page.screenshot({ path: output + "/work-editor.png" });
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("dialog[open]").count(), 0);

  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("http://127.0.0.1:18100/tasks/concept-library");
  await page.locator(".chapter-cover").first().click();
  await page.getByRole("button", { name: "Next →", exact: true }).evaluate((el) => el.click());
  assert.deepEqual(await running(), []);
  await page.goto("http://127.0.0.1:18100/submit?edit=fixture-submission");
  await page.getByRole("button", { name: "A small pause, a warm welcome back.", exact: true }).click();
  await page.getByLabel("Work title", { exact: true }).fill("An edited draft");
  assert.deepEqual(await running(), []);
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("button", { name: "An edited draft", exact: true }).count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Menu", exact: true }).click();
  assert(await page.getByRole("link", { name: "Discovery", exact: true }).isVisible());
  assert.deepEqual(await running(), []);
  await page.screenshot({ path: output + "/mobile-reduced-motion.png" });
  assert.deepEqual(errors, []);
  evidence.reducedMotion = "No running animations; reading, editing, Escape and mobile navigation remain functional.";
  fs.writeFileSync(output + "/checks.json", JSON.stringify({ ...evidence, errors }, null, 2));
} finally {
  await context.close();
  await browser.close();
}
console.log("Motion review passed: paper hover, page turn, selection, dialog, reduced motion and mobile menu. Screenshots saved in " + output + ".");
